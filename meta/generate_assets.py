#!/usr/bin/env python3
"""Deterministic ORIGINAL packaging art for FoldQuest (no third-party assets): icon.png (48x48),
banner.png (256x128) and banner.bnr (CBMD, generated by the shared encoder with a procedural chime).
Usage: generate_assets.py OUTDIR"""
import os
import struct
import sys
import zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from generate_bnr_shared import draw_banner_text_centered, write_cbmd_bnr  # noqa: E402


def write_png(path, width, height, rgba):
    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    rows = bytearray()
    for y in range(height):
        rows.append(0)
        rows.extend(rgba[y * width * 4:(y + 1) * width * 4])
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)) +
                chunk(b"IDAT", zlib.compress(bytes(rows), 9)) + chunk(b"IEND", b""))


def fold_pixel(x, y, w, h):
    """A 'clamshell': two panels split by a crease; the lower panel is shifted/shaded."""
    mid = h // 2
    if abs(y - mid) <= 1:
        return (255, 230, 90, 255)            # crease
    if y < mid:
        return (60 + x * 40 // w, 90, 170, 255) if (x // 6 + y // 6) % 2 else (50 + x * 40 // w, 80, 150, 255)
    return (200, 110 + x * 40 // w, 60, 255) if (x // 6 + y // 6) % 2 else (180, 95 + x * 40 // w, 50, 255)


def icon(path):
    w = h = 48
    buf = bytearray()
    for y in range(h):
        for x in range(w):
            edge = x < 2 or y < 2 or x >= w - 2 or y >= h - 2
            buf += bytes((250, 250, 250, 255) if edge else fold_pixel(x, y, w, h))
    write_png(path, w, h, bytes(buf))


def banner(path):
    w, h = 256, 128
    buf = bytearray()
    for y in range(h):
        for x in range(w):
            buf += bytes(fold_pixel(x, y // 2 + (h // 4 if y >= h // 2 else 0), w, h)) if y < 70 else bytes((16, 18, 30, 255))
    draw_banner_text_centered(buf, w, h, 78, "FOLDQUEST", 3, (255, 220, 100, 255))
    draw_banner_text_centered(buf, w, h, 108, "CLOSE THE LID TO FOLD", 1, (215, 235, 255, 255))
    write_png(path, w, h, bytes(buf))
    return bytes(buf)


def main():
    out = sys.argv[1] if len(sys.argv) == 2 else None
    if not out:
        sys.exit("usage: generate_assets.py OUTDIR")
    os.makedirs(out, exist_ok=True)
    icon(os.path.join(out, "icon.png"))
    rgba = banner(os.path.join(out, "banner.png"))
    write_cbmd_bnr(os.path.join(out, "banner.bnr"), (392.0, 523.25, 659.25), rgba)
    print("Generated FoldQuest icon.png, banner.png, banner.bnr in", out)


if __name__ == "__main__":
    main()
